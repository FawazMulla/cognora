import { NextResponse } from 'next/server';
import { AcademicEventBus } from '../../../../lib/cic/cross-feature/event-bus';
import { RemediationEngine } from '../../../../lib/cic/cross-feature/remediation-engine';
import { db } from '../../../../db';
import { studentTopicProfiles, resources } from '../../../../db/schema';
import { eq, and } from 'drizzle-orm';
import { ATLAS_SUBJECTS } from '../../../../lib/atlasCatalogue';

export const dynamic = 'force-dynamic';

export async function GET(request: Request) {
  try {
    const userId = request.headers.get('x-user-id') || '00000000-0000-0000-0000-000000000101';
    const { searchParams } = new URL(request.url);
    const topicId = searchParams.get('topicId');

    // 1. Fetch active opportunities generated by recent user actions
    const opportunities = AcademicEventBus.getOpportunities(userId);

    // 2. Fetch specific struggle diagnosis if topicId is specified
    let struggleDiagnosis = null;
    if (topicId) {
      struggleDiagnosis = await RemediationEngine.diagnoseStruggle(userId, topicId);
    }

    // 3. Fetch weak topics across the student's profile for global cross-feature recommendations
    let weakTopics: Array<{ topic: string; confidence: number; reason: string | null }> = [];
    try {
      const dbWeak = await db
        .select()
        .from(studentTopicProfiles)
        .where(
          and(
            eq(studentTopicProfiles.userId, userId),
            eq(studentTopicProfiles.weakFlag, 'weak')
          )
        )
        .limit(5);

      weakTopics = dbWeak.map((w) => ({
        topic: w.topic,
        confidence: w.confidence ?? 50,
        reason: w.weakReason,
      }));
    } catch (e) {
      // In-memory fallback
    }

    return NextResponse.json({
      success: true,
      opportunities,
      struggleDiagnosis,
      weakTopicsSummary: weakTopics,
      crossFeatureLinks: {
        smartRevisionDueCount: opportunities.filter((o) => o.type === 'smart_revision').length,
        pyqChallengesCount: opportunities.filter((o) => o.type === 'pyq_recommendation').length,
        remediationActiveCount: opportunities.filter((o) => o.type === 'remediation').length,
      },
    }, { status: 200 });
  } catch (error: any) {
    console.error('[API /intelligence/recommendations GET] Error:', error);
    return NextResponse.json({ error: error.message || 'Failed to fetch cross-feature recommendations' }, { status: 500 });
  }
}
